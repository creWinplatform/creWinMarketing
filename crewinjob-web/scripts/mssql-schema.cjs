// Generates the SQL Server schema from the SQLite schema that the migrations in lib/platform/database.ts build,
// so the two never drift: node scripts/mssql-schema.cjs > lib/db/mssql-schema.sql
// Mapping rules (SQLite → SQL Server):
// - TEXT in a key, index or foreign key → NVARCHAR(KEY_CHARS); other TEXT → NVARCHAR(MAX). NVARCHAR matches the driver's string
//   parameters (no conversion that would turn an index seek into a scan) and keeps Unicode whatever the database collation is.
//   BIN2 keeps SQLite's case-sensitive comparison and byte ordering; COLLATE NOCASE becomes a case-insensitive collation.
// - INTEGER → BIGINT, REAL → FLOAT, BLOB → VARBINARY(MAX). A single INTEGER primary key becomes IDENTITY, like SQLite's rowid alias.
// - Tables without an INTEGER primary key get a `rowid BIGINT IDENTITY` column, so `ORDER BY rowid` keeps insertion order.
// - Primary keys are NONCLUSTERED so composite text keys may use up to 1700 bytes; CHECK constraints are translated.
const { load } = require('../test/platform-loader.cjs');
const { openPlatformDatabase } = load('database.ts');

const BIN = 'Latin1_General_100_BIN2', NOCASE = 'Latin1_General_100_CI_AS_SC';
const db = openPlatformDatabase(':memory:');
const version = db.prepare('SELECT MAX(version) n FROM platform_migrations').get().n;
const tables = db.prepare("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all();
const q = name => `[${name}]`;

// Every key-like column in the schema, and the widest key, decide one key width that fits SQL Server's 1700-byte index limit.
const keyColumns = new Map(), info = {};
const markKey = (table, column) => { if (!keyColumns.has(table)) keyColumns.set(table, new Set()); keyColumns.get(table).add(column); };
let widest = 1;
for (const { name } of tables) {
  info[name] = {
    columns: db.prepare(`PRAGMA table_info(${q(name)})`).all(),
    indexes: db.prepare(`PRAGMA index_list(${q(name)})`).all().map(index => ({ ...index, columns: db.prepare(`PRAGMA index_info(${q(index.name)})`).all().map(c => c.name) })),
    foreignKeys: db.prepare(`PRAGMA foreign_key_list(${q(name)})`).all(),
  };
  const pk = info[name].columns.filter(c => c.pk).sort((a, b) => a.pk - b.pk).map(c => c.name);
  for (const index of [...info[name].indexes.map(i => i.columns), pk]) {
    const text = index.filter(column => /TEXT|^$/i.test(info[name].columns.find(c => c.name === column)?.type || ''));
    widest = Math.max(widest, text.length);
    for (const column of index) markKey(name, column);
  }
  for (const fk of info[name].foreignKeys) { markKey(name, fk.from); markKey(fk.table, fk.to || 'id'); }
}
const KEY_CHARS = Math.min(450, Math.floor(1700 / 2 / widest / 10) * 10);

// CHECK(...) clauses with balanced parentheses, from the CREATE TABLE text.
function checks(sql) {
  const out = []; const re = /CHECK\s*\(/gi; let m;
  while ((m = re.exec(sql))) {
    let depth = 1, i = re.lastIndex;
    while (i < sql.length && depth) { if (sql[i] === '(') depth++; else if (sql[i] === ')') depth--; i++; }
    out.push(sql.slice(re.lastIndex, i - 1));
  }
  return out;
}
// SQLite functions to T-SQL; GLOB becomes LIKE (the BIN2 collation keeps it case-sensitive); column names are bracketed
// outside string literals, so a column called `key` still parses.
function tsql(expr, columns = []) {
  return expr.split(/('(?:[^']|'')*')/).map((part, i) => {
    if (i % 2) return part;
    let out = part.replace(/\blength\s*\(/gi, 'LEN(').replace(/\bIFNULL\s*\(/gi, 'COALESCE(').replace(/\bsubstr\s*\(/gi, 'SUBSTRING(').replace(/\bGLOB\b/g, 'LIKE');
    for (const name of columns) out = out.replace(new RegExp(`(?<![\\w\\[])${name}(?![\\w\\]])`, 'g'), `[${name}]`);
    return out;
  }).join('').replace(/LIKE\s+'((?:[^']|'')*)'/g, (_, pattern) => `LIKE '${pattern.replace(/[_%]/g, '[$&]').replace(/\*/g, '%').replace(/\?/g, '_')}'`);
}
const literal = value => value == null ? null : /^'.*'$|^-?\d+(\.\d+)?$/.test(value) ? value : /^\(.*\)$/.test(value) ? value : `'${value}'`;

function columnType(table, column, nocase) {
  const type = (column.type || '').toUpperCase();
  if (type.includes('INT')) return 'BIGINT';
  if (type.includes('REAL') || type.includes('FLOA') || type.includes('DOUB')) return 'FLOAT';
  if (type.includes('BLOB')) return 'VARBINARY(MAX)';
  const key = keyColumns.get(table)?.has(column.name);
  return `NVARCHAR(${key ? KEY_CHARS : 'MAX'}) COLLATE ${nocase ? NOCASE : BIN}`;
}

const out = [`-- Generated by scripts/mssql-schema.cjs from SQLite schema version ${version}. Do not edit by hand.`, `-- Key text columns: NVARCHAR(${KEY_CHARS}).`, ''];
const foreignKeys = [], indexes = [];
for (const { name, sql } of tables) {
  const { columns } = info[name];
  const pk = columns.filter(c => c.pk).sort((a, b) => a.pk - b.pk);
  const identity = pk.length === 1 && /INT/i.test(pk[0].type) ? pk[0].name : null;
  const lines = [];
  for (const column of columns) {
    const nocase = new RegExp(`\\b${column.name}\\b[^,]*COLLATE\\s+NOCASE`, 'i').test(sql);
    let line = `  ${q(column.name)} ${columnType(name, column, nocase)}`;
    if (column.name === identity) line += ' IDENTITY(1,1)';
    if (column.notnull || column.pk) line += ' NOT NULL';
    if (column.dflt_value != null && column.name !== identity) line += ` DEFAULT ${tsql(literal(column.dflt_value))}`;
    lines.push(line);
  }
  if (!identity && !columns.some(c => c.name === 'rowid')) lines.push('  [rowid] BIGINT IDENTITY(1,1) NOT NULL');
  if (pk.length) lines.push(`  CONSTRAINT ${q(`pk_${name}`)} PRIMARY KEY NONCLUSTERED (${pk.map(c => q(c.name)).join(', ')})`);
  checks(sql).forEach((expr, i) => lines.push(`  CONSTRAINT ${q(`ck_${name}_${i + 1}`)} CHECK (${tsql(expr, columns.map(c => c.name))})`));
  out.push(`CREATE TABLE ${q(name)} (\n${lines.join(',\n')}\n);`);
  // Unique constraints and indexes from the schema (sqlite_autoindex_* are UNIQUE column/table constraints).
  for (const index of info[name].indexes) {
    if (index.origin === 'pk') continue;
    const indexSql = index.origin === 'c' ? db.prepare("SELECT sql FROM sqlite_master WHERE type='index' AND name=?").get(index.name)?.sql || '' : '';
    const where = /\bWHERE\b([\s\S]*)$/i.exec(indexSql)?.[1]?.trim().replace(/;$/, '');
    const label = index.origin === 'c' ? index.name : `uq_${name}_${index.columns.join('_')}`;
    // SQLite lets any number of rows share NULL in a UNIQUE column; SQL Server allows one. A unique index over a
    // nullable column therefore covers only the rows where those columns are set.
    const nullable = index.unique ? index.columns.filter(column => { const c = info[name].columns.find(x => x.name === column); return c && !c.notnull && !c.pk; }) : [];
    const filters = [where ? `(${tsql(where, info[name].columns.map(c => c.name))})` : null, ...nullable.map(column => `${q(column)} IS NOT NULL`)].filter(Boolean);
    indexes.push(`CREATE ${index.unique ? 'UNIQUE ' : ''}NONCLUSTERED INDEX ${q(label.slice(0, 128))} ON ${q(name)} (${index.columns.map(q).join(', ')})${filters.length ? ` WHERE ${filters.join(' AND ')}` : ''};`);
  }
  const groups = new Map();
  for (const fk of info[name].foreignKeys) { if (!groups.has(fk.id)) groups.set(fk.id, []); groups.get(fk.id).push(fk); }
  for (const [id, parts] of groups) {
    const action = parts[0].on_delete && parts[0].on_delete !== 'NO ACTION' ? ` ON DELETE ${parts[0].on_delete}` : '';
    foreignKeys.push(`ALTER TABLE ${q(name)} ADD CONSTRAINT ${q(`fk_${name}_${id}`)} FOREIGN KEY (${parts.map(p => q(p.from)).join(', ')}) REFERENCES ${q(parts[0].table)} (${parts.map(p => q(p.to || 'id')).join(', ')})${action};`);
  }
}
out.push('', ...indexes, '', ...foreignKeys, '');
process.stdout.write(out.join('\n'));
